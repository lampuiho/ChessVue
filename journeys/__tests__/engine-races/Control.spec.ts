import { afterEach, expect, it, vi } from 'vitest';
import { ScriptedEngine } from '../../runtime/engine/ScriptedEngine';
import { JourneyEngineBarrier } from '../../runtime/engine/JourneyEngineBarrier';
afterEach(() => vi.useRealTimers());
it('holds work without timers, drains a held stop and prevents settled release crossing searches', async () => {
  vi.useFakeTimers();
  const control = new JourneyEngineBarrier();
  control.hold('analysis');
  control.holdStops(true);
  const engine = new ScriptedEngine('journey://a', control);
  const lines: string[] = [];
  engine.stdout.on('data', (chunk) => lines.push(String(chunk).trim()));
  engine.stdin.write('go infinite');
  await vi.advanceTimersByTimeAsync(10000);
  expect(lines).toEqual([]);
  expect(engine.diagnostics().pendingTimer).toBe(false);
  engine.stdin.write('stop');
  expect(control.searches()[0]?.pending).toBe(true);
  control.release(1);
  await Promise.resolve();
  expect(lines.at(-1)).toMatch(/^bestmove /);
  engine.stdin.write('go infinite');
  const count = lines.length;
  control.release(1);
  expect(lines).toHaveLength(count);
  control.release(2);
  expect(lines).toHaveLength(count + 3);
  control.reset();
  expect(control.searches().every((entry) => !entry.pending)).toBe(true);
  expect(engine.diagnostics()).toMatchObject({ closed: true, pendingTimer: false, searching: false });
});
it('resets scoped failures and barriers and permits a clean subsequent spawn', async () => {
  const control = new JourneyEngineBarrier();
  control.failNext('journey://a', 2);
  control.hold('player');
  control.holdStops(true);
  expect(control.consumeFailure('journey://b')).toBe(false);
  expect(control.consumeFailure('journey://a')).toBe(true);
  control.reset();
  expect(control.consumeFailure('journey://a')).toBe(false);
  expect(control.isHeld('player')).toBe(false);
  expect(control.stopHeld).toBe(false);
  const engine = new ScriptedEngine('journey://a', control);
  const spawned = vi.fn();
  engine.once('spawn', spawned);
  await Promise.resolve();
  expect(spawned).toHaveBeenCalledOnce();
  engine.kill();
});
