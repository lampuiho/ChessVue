import { flushPromises } from '@vue/test-utils';
import { expect, it, vi } from 'vitest';
import type { IGame } from '@/contracts';
import { boot } from '../support/UiHarness';
it('JRN-RACE-08 disposes a runtime blocked on stop acknowledgement and rejects queued startup', async () => {
  const { api, games, domain } = await boot('engine-races');
  const game = games.getGame('race-analysis') as IGame;
  api.engines.hold('analysis');
  await games.refreshAnalysis(game);
  const engine = game.analysis.seats[0]!.assignedEngine;
  const search = api.engines.searches().filter((entry) => entry.path === 'journey://a').at(-1)!;
  api.engines.holdStops(true);
  const pending = games.retryAnalysis(game, 0);
  await flushPromises();
  expect(engine.$?.analysisClientWork).toBeDefined();
  await domain.EngineRuntimeService.stopEngine(engine);
  await pending;
  api.engines.holdStops(false);
  await flushPromises();
  expect(engine.$).toMatchObject({ availability: 'unavailable', analysisNeedsStop: false });
  expect(engine.$?.processHandle).toBeUndefined();
  expect(engine.$?.analysisClientWork).toBeUndefined();
  expect(engine.$?.analysisCallback).toBeUndefined();
  expect(api.engines.processes().find((entry) => entry.id === search.processId)).toMatchObject({ closed: true, pendingTimer: false, searching: false, listeners: 0 });
  expect(api.engines.searches().find((entry) => entry.id === search.id)?.pending).toBe(false);
  const before = JSON.stringify(game.analysis);
  const revision = games.workspaceRevision;
  api.engines.emit(search.id, 'info depth 99 score cp 999 pv g1f3');
  api.engines.emit(search.id, 'bestmove g1f3');
  await flushPromises();
  expect(JSON.stringify(game.analysis)).toBe(before);
  expect(games.workspaceRevision).toBe(revision);
  await games.retryAnalysis(game, 0);
  await vi.waitFor(() => expect(engine.$?.availability).toBe('running'));
});
