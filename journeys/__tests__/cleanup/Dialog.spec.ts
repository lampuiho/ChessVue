import { flushPromises } from '@vue/test-utils';
import { expect, it, vi } from 'vitest';
import { PlayerColour, PlayerType, type IGame } from '@/contracts';
import { Deferred } from '@/utility/async/Deferred';
import { boot, clickButton } from '../support/UiHarness';
it.each(['success', 'failure'])('keeps a replacement dialog intact after late action %s', async (outcome) => {
  const { modal, games, api } = await boot('play');
  const { default: GameCreationModal } = await import('@/components/modals/GameCreationModal.vue');
  const pending = new Deferred<void>();
  vi.spyOn(games, 'reassignPlayer').mockImplementationOnce(() => pending);
  const { default: PlayerSelectionModal } = await import('@/components/modals/PlayerSelectionModal.vue');
  const dialog = modal.open(PlayerSelectionModal, { gameId: api.gameIds[0]!, colour: PlayerColour.White });
  await flushPromises();
  const signal = dialog.signal;
  await clickButton('Assign player', '.modal-card button');
  expect(games.reassignPlayer).toHaveBeenCalledTimes(1);
  await dialog.close();
  expect(signal.aborted).toBe(true);
  modal.open(GameCreationModal, {});
  if (outcome === 'success') pending.resolve();
  else pending.reject(new Error('Old action failed'));
  await flushPromises();
  expect(document.querySelector('[role=dialog]')?.textContent).toContain('Set up a new board');
  expect(document.querySelector('.inline-message--error')).toBeNull();
  expect(document.querySelector<HTMLButtonElement>('button[form="new-game-form"]')!.disabled).toBe(false);
});
it('does not navigate when a dismissed create action completes', async () => {
  const { modal, games, api, router } = await boot('play');
  const { default: GameCreationModal } = await import('@/components/modals/GameCreationModal.vue');
  const pending = new Deferred<IGame>();
  const originalRoute = router.currentRoute.value.fullPath;
  vi.spyOn(games, 'createGame').mockImplementationOnce(() => pending);
  const dialog = modal.open(GameCreationModal, {});
  await flushPromises();
  await clickButton('Create workspace', '.modal-card button');
  expect(games.createGame).toHaveBeenCalledTimes(1);
  await dialog.close();
  const { default: ConfirmationModal } = await import('@/components/modals/ConfirmationModal.vue');
  modal.open(ConfirmationModal, { title: 'Reset all settings?', confirmLabel: 'Reset settings', confirm: async () => {} });
  pending.resolve(games.getGame(api.gameIds[0]!) as unknown as IGame);
  await flushPromises();
  expect(router.currentRoute.value.fullPath).toBe(originalRoute);
  expect(document.querySelector('[role=dialog]')?.textContent).toContain('Reset all settings?');
});
