import { flushPromises } from '@vue/test-utils';
import { expect, it, vi } from 'vitest';
import { Deferred } from '@/utility/async/Deferred';
import { boot, clickButton, clickSquare, createTimedContext, legalMove, setField } from '../support/UiHarness';
function _dialog(title: string) {
  const dialog = document.querySelector<HTMLElement>(`[role="dialog"][aria-label="${title}"]`);
  expect(dialog).not.toBeNull();
  expect(dialog!.closest('main') === null).toBe(true);
  return dialog!;
}
it('mounts board promotion as an owned dialog and clears it on board unmount', async () => {
  const { games, api, router } = await boot('promotion');
  await clickSquare('a7');
  await clickSquare('a8');
  _dialog('Choose promotion');
  const game = games.getGame(api.gameIds[0]!)!;
  expect(game.moveTree.root.children).toHaveLength(0);
  await router.push('/home');
  await flushPromises();
  expect(document.querySelector('[role="dialog"]')).toBeNull();
  expect(game.moveTree.root.children).toHaveLength(0);
});
it('hands a drawer action to a replacement modal and clears it on route unmount', async () => {
  const { router, modal } = await boot('play');
  document.querySelector<HTMLButtonElement>('.navigation-toggle--mobile')!.click();
  await flushPromises();
  _dialog('Navigation menu');
  const { default: MessageModal } = await import('@/components/modals/MessageModal.vue');
  const notice = modal.open(MessageModal, { title: 'Replacement', message: 'Owned replacement' });
  expect(document.querySelector('[aria-label="Navigation menu"]')).toBeNull();
  await notice.close();
  document.querySelector<HTMLButtonElement>('.navigation-toggle--mobile')!.click();
  await flushPromises();
  await clickButton('Custom', '.navigation-drawer button');
  _dialog('Set up a new board');
  expect(document.querySelectorAll('[role="dialog"]')).toHaveLength(1);
  await clickButton('Cancel', '.modal-card button');
  document.querySelector<HTMLButtonElement>('.navigation-toggle--mobile')!.click();
  await flushPromises();
  await router.push('/settings/session');
  await flushPromises();
  expect(document.querySelector('[role="dialog"]')).toBeNull();
});
it('mounts history confirmation separately and cancels its captured continuation on navigation', async () => {
  const context = await createTimedContext();
  const { game, games } = context;
  await games.makeMove(game, legalMove(context, game, 'e2e4'));
  games.navigateToNode(game, game.moveTree.root);
  await flushPromises();
  await clickSquare('d2');
  await clickSquare('d4');
  _dialog('Continue from this position?');
  await context.router.push('/home');
  await flushPromises();
  expect(document.querySelector('[role="dialog"]')).toBeNull();
  expect(game.livePath).toEqual([0]);
});
it('keeps engine-editor validation and draft changes inside its mounted form', async () => {
  const { stores, router } = await boot('settings');
  await router.push('/settings/engines');
  await flushPromises();
  const before = stores.useSettingsStore().draftSettings!.analysis.engineInventory.length;
  await clickButton('Add profile', '.settings-content button, .settings-page button');
  await vi.waitFor(() => expect(router.currentRoute.value.name).toBe('engine-profile-new'));
  await vi.waitFor(() => expect(document.querySelector('#engine-name')).not.toBeNull());
  const editor = document.querySelector('.engine-editor')!;
  expect(document.querySelector('[role="dialog"]')).toBeNull();
  await clickButton('Add profile', '.engine-editor button');
  expect(editor.textContent).toContain('Profile name is required');
  setField('#engine-name', 'New owned profile');
  await clickButton('Add profile', '.engine-editor button');
  expect(document.querySelector('[role="dialog"]')).toBeNull();
  expect(stores.useSettingsStore().draftSettings!.analysis.engineInventory).toHaveLength(before + 1);
});
it('retains overwrite intent and dismissal lock while a mounted confirmation writes', async () => {
  const { stores, router } = await boot('storage-failures');
  await router.push('/saved-games/save/io-game');
  await flushPromises();
  setField('#save-name', 'Opening');
  await clickButton('Save game', '.library-actions button');
  const dialog = _dialog('Replace this save?');
  const pending = new Deferred<string>();
  const saved = stores.useSavedGamesStore();
  const write = vi.spyOn(saved, 'saveGame').mockImplementationOnce(() => pending);
  const confirm = [...dialog.querySelectorAll('button')].find((button) => button.textContent === 'Replace save')!;
  confirm.click();
  confirm.click();
  await flushPromises();
  dialog.dispatchEvent(new KeyboardEvent('keydown', { key: 'Escape', bubbles: true }));
  expect(dialog.isConnected).toBe(true);
  expect(write).toHaveBeenCalledTimes(1);
  pending.resolve('saves/io-game/Opening.json');
  await flushPromises();
  expect(document.querySelector('[role="dialog"]')).toBeNull();
});
it('captures one saved snapshot for a mounted deletion confirmation', async () => {
  const { stores, router } = await boot('saves');
  const saved = stores.useSavedGamesStore();
  const groups = await saved.listSavedGames();
  const group = groups.find((candidate) => candidate.saves.some((entry) => !entry.isAutosave))!;
  const entry = group.saves.find((candidate) => !candidate.isAutosave)!;
  await router.push('/saved-games/load/' + group.gameId);
  await flushPromises();
  const row = [...document.querySelectorAll('.save-row')].find((candidate) => candidate.querySelector('strong')?.textContent === entry.saveName)!;
  row.querySelector<HTMLButtonElement>('[title="Delete save"]')!.click();
  await flushPromises();
  _dialog('Delete this save?');
  const remove = vi.spyOn(saved, 'deleteSave');
  await clickButton('Delete save', '.modal-card button');
  expect(remove).toHaveBeenCalledExactlyOnceWith(entry.gameId, entry.saveName);
  expect(document.querySelector('[role="dialog"]')).toBeNull();
});
