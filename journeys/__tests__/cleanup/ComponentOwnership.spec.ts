it('uses the same accepted quick defaults from Home and the game menu', async () => {
  const { games, router, stores } = await boot('fresh');
  const settings = stores.useSettingsStore();
  settings.draftSettings!.gameDefaults.name = 'Shared quick defaults';
  settings.draftSettings!.gameDefaults.timeControl = { initialMs: 180000, incrementMs: 2000 };
  await settings.applySettings();
  const create = vi.spyOn(games, 'createGame');
  await clickButton('Quick game', '.home-actions button');
  await vi.waitFor(() => expect(router.currentRoute.value.path).toMatch(/^\/game\//));
  const firstRoute = router.currentRoute.value.path;
  await clickButton('Quick game', '.navigation-frame button');
  await vi.waitFor(() => expect(router.currentRoute.value.path).not.toBe(firstRoute));
  expect(create).toHaveBeenCalledTimes(2);
  expect(create.mock.calls[1]![0]).toEqual(create.mock.calls[0]![0]);
  expect(create.mock.calls[1]![0]).toMatchObject({ name: 'Shared quick defaults', whitePlayer: { type: PlayerType.Local }, blackPlayer: { type: PlayerType.Local }, timeControl: { initialMs: 180000, incrementMs: 2000 } });
  expect(stores.useUiStateStore().gameSession?.openGameIds).toHaveLength(2);
});
