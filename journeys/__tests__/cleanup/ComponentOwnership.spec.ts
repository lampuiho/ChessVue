it.each(['engine', 'both engines', 'unassigned', 'analysis'])('uses independent %s snapshots for Home, menu and unchanged Custom creation', async (mode) => {
  const { games, router, stores, domain } = await boot('fresh');
  const settings = stores.useSettingsStore();
  const engine = { id: 'saved', displayName: 'Saved A', clientType: EngineClientType.Uci, entryPath: 'journey://a', options: { Threads: 1 } };
  const defaults = settings.draftSettings!.gameDefaults;
  defaults.blackPlayer = mode.includes('engine') ? createEnginePlayer(engine, PlayerColour.Black) : undefined;
  if (mode === 'both engines') defaults.whitePlayer = createEnginePlayer(engine, PlayerColour.White);
  if (mode === 'analysis') defaults.whitePlayer = undefined;
  defaults.analysisEngineProfiles = [engine];
  defaults.allowTakeback = false;
  defaults.showLiveAnalysisMoves = true;
  await settings.applySettings();
  const create = vi.spyOn(games, 'createGame');
  await clickButton('Quick game', '.home-actions button');
  await vi.waitFor(() => expect(router.currentRoute.value.path).toMatch(/^\/game\//));
  await clickButton('Quick game', '.navigation-frame button');
  await vi.waitFor(() => expect(create).toHaveBeenCalledTimes(2));
  await clickButton('Custom', '.navigation-frame button');
  document.querySelector<HTMLFormElement>('#new-game-form')!.dispatchEvent(new Event('submit', { bubbles: true, cancelable: true }));
  await vi.waitFor(() => expect(create).toHaveBeenCalledTimes(3));
  expect(create.mock.calls[1]![0]).toEqual(create.mock.calls[0]![0]);
  expect(create.mock.calls[2]![0]).toEqual(create.mock.calls[0]![0]);
  const game = games.listGames()[0]!;
  expect(game.gameplayOptions).toMatchObject({ allowTakeback: false, showLiveAnalysisMoves: true });
  expect(game.analysis.seats[0]!.assignedEngine.entryPath).toBe('journey://a');
  expect(settings.settings!.gameDefaults.analysisEngineProfiles[0]!.options.Threads).toBe(1);
  await Promise.all(games.listGames().flatMap(current => [current.whitePlayer, current.blackPlayer]).filter(player => player?.type === PlayerType.Engine).map(player => domain.EngineRuntimeService.stopEngine((player as import('@/contracts').IEnginePlayer).assignedEngine)));
});
