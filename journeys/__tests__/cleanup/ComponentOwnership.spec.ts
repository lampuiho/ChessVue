it.each(['active', 'background'])('keeps rejected selection committed and closes a real %s tab without disposing the game', async (target) => {
  const { games, router, stores, game } = await createTimedContext();
  const other = await games.createGame({ name: 'Other tab', whitePlayer: { colour: PlayerColour.White, type: PlayerType.Local, displayName: 'White' }, blackPlayer: { colour: PlayerColour.Black, type: PlayerType.Local, displayName: 'Black' }, analysisEngineProfiles: [], timeControl: { preset: TimeControlPreset.Untimed, incrementMs: 0 } });
  const ui = stores.useUiStateStore();
  ui.openTab(other.metadata.id);
  ui.setActiveGame(game.metadata.id);
  await nextTick();
  const reject = router.beforeEach((to) => to.path === `/game/${other.metadata.id}` ? false : undefined);
  const select = document.querySelector<HTMLElement>('[title="Other tab"]')!.closest('button')!;
  select.click();
  await flushPromises();
  expect(router.currentRoute.value.path).toBe(`/game/${game.metadata.id}`);
  expect(ui.gameSession?.activeGameId).toBe(game.metadata.id);
  expect(document.querySelector('.tab-button--active')?.textContent).toContain(game.metadata.name);
  reject();
  const closing = target === 'active' ? game : other;
  const survivor = target === 'active' ? other : game;
  const clear = vi.spyOn(games, 'clearPremoves');
  document.querySelector<HTMLElement>(`[aria-label="Close ${closing.metadata.name}"]`)!.click();
  await flushPromises();
  expect(clear).toHaveBeenCalledExactlyOnceWith(closing);
  expect(ui.gameSession?.openGameIds).toEqual([survivor.metadata.id]);
  expect(games.getGame(closing.metadata.id)).toBe(closing);
  await clickButton('Close game', '.navigation-frame button');
  expect(ui.gameSession?.openGameIds).toEqual([]);
  expect(router.currentRoute.value.path).toBe('/home');
  expect(games.listGames()).toHaveLength(2);
});
it('filters engine choices from canonical assignments added after the chooser opens', async () => {
  const { games, modal, stores, api, domain } = await boot('analysis');
  const game = games.getGame(api.gameIds[0]!) as IGame;
  const profiles = stores.useSettingsStore().settings!.analysis.engineInventory;
  const available = profiles.find((profile) => !game.analysis.seats.some((seat) => seat.assignedEngine.displayName === profile.displayName))!;
  const { default: AnalysisEngineSelectionModal } = await import('@/components/modals/AnalysisEngineSelectionModal.vue');
  modal.open(AnalysisEngineSelectionModal, { gameId: game.metadata.id });
  await nextTick();
  const choices = () => [...document.querySelectorAll('.choice-card strong')].map((choice) => choice.textContent);
  expect(choices()).toContain(available.displayName);
  for (const seat of game.analysis.seats) expect(choices()).not.toContain(seat.assignedEngine.displayName);
  await games.addAnalysisEngine(game, { ...available, options: { ...available.options } });
  await nextTick();
  expect(choices()).not.toContain(available.displayName);
  await Promise.all(games.listGames().flatMap((current) => current.analysis.seats).map((seat) => domain.EngineRuntimeService.stopEngine(seat.assignedEngine)));
});
it('dismisses an obsolete draw response and prevents its detached button from affecting a replacement', async () => {
  const { games, game, modal } = await createTimedContext();
  await games.offerDraw(game);
  const { default: DrawResponseModal } = await import('@/components/modals/DrawResponseModal.vue');
  const handle = modal.open(DrawResponseModal, { gameId: game.metadata.id });
  await nextTick();
  const dialog = document.querySelector<HTMLElement>('[role="dialog"]')!;
  expect(dialog.textContent).toContain('black to respond.');
  const oldAccept = [...dialog.querySelectorAll('button')].find((button) => button.textContent === 'Accept')!;
  const accept = vi.spyOn(games, 'acceptDrawOffer');
  await games.withdrawDrawOffer(game);
  await flushPromises();
  expect(handle.signal.aborted).toBe(true);
  expect(document.querySelector('[role="dialog"]')).toBeNull();
  const { default: MessageModal } = await import('@/components/modals/MessageModal.vue');
  modal.open(MessageModal, { title: 'Replacement', message: 'Still owned' });
  oldAccept.click();
  await flushPromises();
  expect(accept).not.toHaveBeenCalled();
  expect(document.querySelector('[role="dialog"]')?.textContent).toContain('Still owned');
});
