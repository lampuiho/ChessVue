import type { ISettingsSnapshot } from '../../src/contracts';
import { exportGame } from './BrowserAction';

test('saved snapshots start a real Stockfish opponent and analysis after profile deletion and reload', async ({ page }) => {
  test.setTimeout(60000);
  await page.goto('/settings/gameplay');
  await page.getByLabel('Black player', { exact: true }).selectOption('engine:stockfish');
  await page.getByLabel('Add analysis engine', { exact: true }).selectOption('stockfish');
  await page.getByRole('button', { name: 'Add engine', exact: true }).click();
  await page.getByLabel('Clock preset', { exact: true }).selectOption('custom');
  await page.getByLabel('Minutes', { exact: true }).fill('3');
  await page.getByLabel('Increment (seconds)', { exact: true }).fill('2');
  await page.getByText('Allow takebacks', { exact: true }).click();
  await page.getByText('Show live analysis moves', { exact: true }).click();
  await page.getByRole('button', { name: 'Engines', exact: true }).click();
  await page.getByTitle('Delete', { exact: true }).click();
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  await expect(page).toHaveURL(/\/home$/);
  await page.reload();
  const settings = (await browserDocument<ISettingsSnapshot>(page, 'settings.json'))!;
  expect(settings.analysis.engineInventory).toEqual([]);
  expect(settings.gameDefaults.analysisEngineProfiles[0]!.displayName).toBe('Stockfish');
  expect(JSON.stringify(settings)).not.toContain('"$"');
  await page.getByRole('button', { name: /Quick game/ }).click();
  await expect(page).toHaveURL(/\/game\/.+/);
  await expectAnalysis(page, ['Stockfish']);
  await playMove(page, 'e2', 'e4');
  await expect(page.locator('.history-row')).toHaveCount(2, { timeout: 20000 });
  const id = gameId(page);
  await expect.poll(async () => (await browserGame(page, id))?.livePath).toEqual([0, 0]);
  const game = (await browserGame(page, id))!;
  expect(game.blackPlayer?.type).toBe('engine');
  expect(game.timeControl).toEqual({ initialMs: 180000, incrementMs: 2000 });
  expect(game.gameplayOptions).toEqual({ allowTakeback: false, showLiveAnalysisMoves: true });
  await page.getByRole('button', { name: 'Custom', exact: true }).click();
  const dialog = page.getByRole('dialog');
  await expect(dialog.getByLabel('Black', { exact: true })).toHaveValue('keep');
  await expect(dialog.getByLabel('Clock', { exact: true })).toHaveValue('custom');
  await expect(dialog.getByLabel('Minutes', { exact: true })).toHaveValue('3');
  await expect(dialog.getByLabel('Saved analysis engine 1', { exact: false })).toHaveValue('');
});

test('package removal sees saved default paths after their reusable profile is deleted', async ({ page }) => {
  await page.goto('/settings/engines');
  await page.evaluate(async () => {
    const modulePath = '/src/domain/EnginePackageService.ts';
    const { EnginePackageService } = await import(modulePath);
    await EnginePackageService.install('Default package', { files: [{ path: 'engine.js', data: new TextEncoder().encode('onmessage=()=>{};') }] });
  });
  await page.getByRole('button', { name: 'Refresh', exact: true }).click();
  const item = page.locator('.engine-package-list__item').filter({ hasText: 'Default package' });
  await item.getByRole('button', { name: 'Create profile', exact: true }).click();
  await page.getByLabel('Profile name').fill('Saved package');
  await page.locator('#engine-entry-file').selectOption('engine-files/Default package/engine.js');
  await page.getByRole('button', { name: 'Add profile', exact: true }).click();
  await page.getByRole('button', { name: 'Gameplay', exact: true }).click();
  await page.getByLabel('Black player', { exact: true }).selectOption({ label: 'Use profile: Saved package' });
  await page.getByRole('button', { name: 'Engines', exact: true }).click();
  await page.locator('.engine-list article').filter({ hasText: 'Saved package' }).getByTitle('Delete', { exact: true }).click();
  await page.getByRole('button', { name: 'Apply changes', exact: true }).click();
  await expect(page.locator('.unsaved-badge')).toHaveCount(0);
  await item.getByRole('button', { name: 'Details', exact: true }).click();
  await expect(page.getByText('Game defaults: black', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Remove files', exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Remove files', exact: true }).click();
  await expect(page.getByRole('dialog').getByRole('alert')).toContainText('Game defaults: black');
});

test('mobile defaults validate Custom values and retain free analysis across reload', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto('/settings/gameplay');
  await page.getByLabel('Clock preset', { exact: true }).selectOption('custom');
  await page.getByLabel('Minutes', { exact: true }).fill('0');
  await expect(page.getByRole('alert')).toContainText('minutes');
  await expect(page.getByRole('button', { name: 'Apply changes', exact: true })).toBeDisabled();
  await page.getByLabel('Minutes', { exact: true }).fill('7');
  await page.getByRole('button', { name: 'Use free analysis', exact: true }).click();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  await expect(page).toHaveURL(/\/home$/);
  await page.reload();
  await page.getByRole('button', { name: /Quick game/ }).click();
  await expect(page).toHaveURL(/\/game\/.+/);
  await playMove(page, 'e2', 'e4');
  const id = gameId(page);
  await expect.poll(async () => (await browserGame(page, id))?.gameState).toBe('analysisBlackMove');
  const game = (await browserGame(page, id))!;
  expect(game.whitePlayer).toBeUndefined();
  expect(game.blackPlayer).toBeUndefined();
  expect(game.clockSnapshot.white.isRunning).toBe(false);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
});

for (const draw of [0.25, 0.75]) {
  test(`random colour defaults assign the participants afresh and preserve resolved colours on reload (draw ${draw})`, async ({ page }) => {
    test.setTimeout(60000);
    await page.addInitScript(value => { Math.random = () => value; }, draw);
    await page.goto('/settings/gameplay');
    await page.getByLabel('Black player', { exact: true }).selectOption('engine:stockfish');
    await page.getByText('Randomly assign colours', { exact: true }).click();
    await expect(page.getByLabel('Player 1', { exact: true })).toHaveValue('local');
    await expect(page.getByLabel('Player 2', { exact: true })).toHaveValue('keep');
    await page.getByRole('button', { name: 'Save', exact: true }).click();
    await expect(page).toHaveURL(/\/home$/);
    await page.reload();
    expect((await browserDocument<ISettingsSnapshot>(page, 'settings.json'))!.gameDefaults.randomiseColours).toBe(true);
    await page.getByRole('button', { name: /Custom game/ }).click();
    const dialog = page.getByRole('dialog');
    await expect(dialog.getByRole('checkbox', { name: /^Randomly assign colours/ })).toBeChecked();
    await expect(dialog.getByLabel('Player 2', { exact: true })).toHaveValue('keep');
    await dialog.getByRole('button', { name: 'Create workspace', exact: true }).click();
    await expect(page).toHaveURL(/\/game\/.+/);
    if (draw >= 0.5) await playMove(page, 'e2', 'e4');
    await expect(page.locator('.history-row')).toHaveCount(draw < 0.5 ? 1 : 2, { timeout: 15000 });
    const first = await exportGame(page);
    expect([first.whitePlayer?.displayName, first.blackPlayer?.displayName]).toEqual(draw < 0.5 ? ['Stockfish', 'Player 1'] : ['Player 1', 'Stockfish']);
    expect([first.whitePlayer?.colour, first.blackPlayer?.colour]).toEqual(['white', 'black']);
    expect(first).not.toHaveProperty('randomiseColours');
    await page.getByRole('button', { name: 'Close', exact: true }).click();
    const previousUrl = page.url();
    await page.evaluate(value => { Math.random = () => value; }, 1 - draw);
    await page.getByRole('button', { name: 'Quick game', exact: true }).click();
    await expect(page).not.toHaveURL(previousUrl);
    await expect(page).toHaveURL(/\/game\/.+/);
    if (draw < 0.5) await playMove(page, 'e2', 'e4');
    await expect(page.locator('.history-row')).toHaveCount(draw < 0.5 ? 2 : 1, { timeout: 15000 });
    const second = await exportGame(page);
    expect([second.whitePlayer?.displayName, second.blackPlayer?.displayName]).toEqual(draw < 0.5 ? ['Player 1', 'Stockfish'] : ['Stockfish', 'Player 1']);
    await page.reload();
    await expect(page.getByRole('button', { name: 'Close', exact: true })).toBeVisible();
    await page.getByRole('button', { name: 'Close', exact: true }).click();
    const restored = await exportGame(page);
    expect([restored.whitePlayer, restored.blackPlayer]).toEqual([second.whitePlayer, second.blackPlayer]);
    const defaults = (await browserDocument<ISettingsSnapshot>(page, 'settings.json'))!.gameDefaults;
    expect(defaults.whitePlayer?.colour).toBe('white');
    expect(defaults.blackPlayer?.colour).toBe('black');
  });
}
