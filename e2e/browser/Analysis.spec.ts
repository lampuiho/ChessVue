import type { Worker } from '@playwright/test';
import { test, expect } from './BrowserTest';
import { configureStockfish, createAnalysis, engineSection, expectAnalysis, expectCurrentAnalysis } from './EngineAction';
import { exportGame } from './BrowserAction';
import { StockfishConfig } from '../../src/config/StockfishConfig';
import { square } from '../support/BoardInteraction';

test('JRN-BROWSER-03 isolates two real workers through stop restart position change and reload with matching WASM', async ({ page }, testInfo) => {
  const workers: Worker[] = [];
  const wasm: string[] = [];
  page.on('worker', (worker) => workers.push(worker));
  page.on('response', (response) => {
    if (response.ok() && new URL(response.url()).pathname.endsWith('/' + StockfishConfig.wasmFile)) wasm.push(response.url());
  });
  await configureStockfish(page, 2);
  const names = ['Browser Stockfish', 'Browser Stockfish 2'];
  await createAnalysis(page, names);
  await expectAnalysis(page, names);
  expect(page.workers()).toHaveLength(2);
  const original = [...page.workers()];
  expect(original[0]).not.toBe(original[1]);
  for (const worker of original) expect(new URL(worker.url()).pathname).toBe(`/engines/stockfish/${StockfishConfig.workerFile}`);
  await expect.poll(() => wasm.length).toBeGreaterThanOrEqual(2);
  await engineSection(page, names[0]!).getByRole('button', { name: 'Stop engine', exact: true }).click();
  await expect(engineSection(page, names[0]!).locator('.engine-section__status--running')).toHaveCount(0);
  await expect(engineSection(page, names[1]!).locator('.engine-section__status--running')).toBeVisible();
  expect(page.workers()).toEqual(original);
  await page.getByRole('button', { name: 'Refresh analysis', exact: true }).click();
  await expectAnalysis(page, names);
  expect(page.workers()).toEqual(original);
  await square(page, 'e2').click();
  const depth = await engineSection(page, names[1]!).locator('.analysis-line small').first().innerText();
  await expect.poll(() => engineSection(page, names[1]!).locator('.analysis-line small').first().innerText()).not.toBe(depth);
  await expect(square(page, 'e4')).toHaveClass(/board-square--target/);
  await square(page, 'e4').click();
  await expect(page.locator('.history-row')).toHaveCount(1);
  await expectAnalysis(page, names);
  expectCurrentAnalysis(await exportGame(page));
  await page.getByRole('button', { name: 'Close', exact: true }).click();
  await page.reload();
  await expect(page.locator('.history-row')).toHaveCount(1);
  await expectAnalysis(page, names);
  expect(page.workers()).toHaveLength(2);
  for (const worker of page.workers()) expect(original).not.toContain(worker);
  await expect.poll(() => wasm.length).toBeGreaterThanOrEqual(4);
  expectCurrentAnalysis(await exportGame(page));
  await expect(page.locator('.engine-error')).toHaveCount(0);
  await testInfo.attach('stockfish-assets', { body: JSON.stringify({ workers: workers.map((worker) => worker.url()), wasm }), contentType: 'application/json' });
});
