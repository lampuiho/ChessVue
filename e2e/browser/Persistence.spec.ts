import { test, expect } from './BrowserTest';
import type { IGameSessionSnapshot, ISettingsSnapshot } from '../../src/contracts';
import { createGame, expectCanonical, exportGame, playOpening, saveNamedGame } from './BrowserAction';
import { browserDocument, browserFiles, browserGame, gameId } from './BrowserStorage';

test('JRN-BROWSER-01 preserves canonical game session and appearance after reload and a new same-origin page', async ({ page, context }) => {
  await createGame(page);
  await playOpening(page);
  const id = gameId(page);
  const url = page.url();
  await saveNamedGame(page, 'Browser opening');
  const named = Object.entries(await browserFiles(page)).find(([path]) => path.startsWith(`saves/${id}/`) && !path.endsWith('/auto.json'))!;
  expect(named).toBeTruthy();
  const original = (await browserGame(page, id))!;
  await page.getByRole('button', { name: 'Close', exact: true }).click();
  await page.getByRole('button', { name: 'Settings', exact: true }).click();
  await page.getByRole('button', { name: 'Appearance', exact: true }).click();
  await page.getByRole('radio', { name: 'dark', exact: true }).check();
  await page.getByLabel('Orientation', { exact: true }).selectOption('black');
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  await expect.poll(async () => (await browserDocument<IGameSessionSnapshot>(page, 'game-session.json'))?.activeRoute).toBe(`/game/${id}`);
  const settings = (await browserDocument<ISettingsSnapshot>(page, 'settings.json'))!;
  expect(settings.appearance).toMatchObject({ themeMode: 'dark', boardOrientation: 'black' });
  await page.reload();
  await expect(page).toHaveURL(url);
  await expect(page.locator('.history-row')).toHaveCount(1);
  expectCanonical(await exportGame(page), original);
  await page.getByRole('button', { name: 'Close', exact: true }).click();
  const reopened = await context.newPage();
  await reopened.goto('/');
  await expect(reopened).toHaveURL(url);
  await expect(reopened.locator('html')).toHaveAttribute('data-theme', 'dark');
  await expect(reopened.locator('.board-square').first()).toHaveAttribute('aria-label', /^h1 /);
  await expect(reopened.locator('.history-row')).toHaveCount(1);
  expectCanonical(await exportGame(reopened), original);
  expect((await browserFiles(reopened))[named[0]]).toBe(named[1]);
  expect(await browserDocument(reopened, 'settings.json')).toEqual(settings);
  expect(await browserDocument(reopened, 'game-session.json')).toMatchObject({ openGameIds: [id], activeGameId: id });
});
