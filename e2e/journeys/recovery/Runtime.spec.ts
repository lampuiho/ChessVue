import { test, expect } from './RecoveryTest';
import { playMove } from '../../support/BoardInteraction';
import { saveCurrentGame } from '../../support/GameSave';
import { choosePlayer } from '../play/PlaySetup';
import { expectSession, openRecovery, reloadRecovery } from './RecoveryAction';
test('JRN-RECOVERY-08 restores an unavailable player with scoped feedback and allows reassignment', async ({ page }) => {
  await openRecovery(page, 'unavailable-player');
  await expectSession(page, ['recovery-valid'], '/game/recovery-valid', 'recovery-valid');
  await expect(page.locator('.player-panel .engine-error')).toContainText('unavailable');
  await expect(page.locator('.recovery-notice')).toHaveCount(0);
  await expect(page.locator('.history-row')).toHaveCount(1);
  await choosePlayer(page, 'Black', 'Local player');
  await expect(page.locator('.player-panel .engine-error')).toHaveCount(0);
  await playMove(page, 'e7', 'e5');
  await expect(page.locator('.history-row')).toHaveCount(2);
  const saved = await saveCurrentGame(page, 'Reassigned');
  expect(saved.livePath).toEqual([0, 0]);
});
test('JRN-RECOVERY-08 isolates an unavailable analysis seat while another engine and the board remain usable', async ({ page }) => {
  await openRecovery(page, 'unavailable-analysis');
  await expect(page.locator('.analysis-panel .engine-error')).toContainText('unavailable');
  await expect(page.locator('.engine-section__status--running')).toHaveCount(1);
  await expect(page.locator('.engine-summary')).toContainText(['Depth 12', 'No principal variation yet']);
  await expect(page.locator('.recovery-notice')).toHaveCount(0);
  await playMove(page, 'e7', 'e5');
  await expect(page.locator('.history-row')).toHaveCount(2);
  await expect(page.locator('.engine-summary').first()).toContainText('Depth 12');
  const saved = await saveCurrentGame(page, 'Analysis failure');
  expect(saved.analysis.seats[0]!.lines).toHaveLength(3);
  expect(saved.analysis.seats[1]!.assignedEngine.displayName).toBe('Journey unavailable');
});
test('JRN-RECOVERY-08 restores a paused engine game without arming a turn until explicit resume', async ({ page }) => {
  await openRecovery(page, 'paused');
  await page.clock.runFor(2000);
  await expect(page.getByRole('button', { name: /Resume game/ })).toBeVisible();
  await expect(page.locator('.history-row')).toHaveCount(1);
  await expect(page.locator('.player-clock span')).toHaveText(['5:00', '5:00']);
  await expect(page.locator('.engine-state--running')).toHaveCount(0);
  await page.getByRole('button', { name: /Resume game/ }).click();
  await expect(page.locator('.history-row')).toHaveCount(2);
  await page.clock.runFor(1000);
  await expect(page.locator('.history-row')).toHaveCount(2);
  await expect(page.locator('.result-badge')).toHaveText('white to move');
});
test('JRN-RECOVERY-08 restores board edit without analysis or player work until editing finishes', async ({ page }) => {
  await openRecovery(page, 'board-edit');
  await page.clock.runFor(1000);
  await expect(page.getByRole('button', { name: /Finish editing/ })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Refresh analysis', exact: true })).toBeDisabled();
  await expect(page.locator('.engine-section__status--running, .engine-error, .history-row')).toHaveCount(0);
  await page.getByRole('button', { name: /Finish editing/ }).click();
  await expect(page.locator('.engine-section__status--running')).toHaveCount(1);
  await expect(page.locator('.analysis-panel .engine-error')).toContainText('unavailable');
  const saved = await saveCurrentGame(page, 'Finished edit');
  expect(saved.livePath).toBeUndefined();
});
test('JRN-RECOVERY-08 arms exactly one restored player reply across navigation and reload', async ({ page }) => {
  await openRecovery(page, 'live-engine');
  await expect(page.locator('.history-row')).toHaveCount(2);
  await page.locator('.app-header').getByRole('button', { name: 'Settings', exact: true }).click();
  await page.getByRole('button', { name: 'Back to game', exact: true }).click();
  await page.clock.runFor(2000);
  await expect(page.locator('.history-row')).toHaveCount(2);
  const saved = await saveCurrentGame(page, 'One reply');
  expect(saved.livePath).toEqual([0, 0]);
  expect(saved.moveTree.root.children[0]!.children).toHaveLength(1);
  await reloadRecovery(page);
  await expect(page.locator('.history-row')).toHaveCount(2);
  await page.clock.runFor(1000);
  await expect(page.locator('.history-row')).toHaveCount(2);
});
