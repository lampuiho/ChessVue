import { test, expect } from './SaveTest';
import { openJourney } from '../../support/JourneyBootstrap';
import { readFile } from '../../support/SaveInspection';
import { square, playMove } from '../../support/BoardInteraction';
import { fileSnapshot, deleteSnapshot, snapshotRow } from './SaveAction';
test('JRN-SAVE-11 cancels deletion without changing the selected snapshot or stored bytes', async ({ page }) => {
  await openJourney(page, 'saves');
  await snapshotRow(page, 'Opening').locator('.save-row__content').click();
  await expect(page.getByLabel('Selected save details')).toContainText('2 plies');
  const before = await fileSnapshot(page);
  await snapshotRow(page, 'Opening').getByRole('button', { name: 'Delete save', exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Cancel', exact: true }).click();
  expect(await fileSnapshot(page)).toEqual(before);
  await expect(page.getByLabel('Selected save details')).toContainText('2 plies');
  await expect(snapshotRow(page, 'Opening').locator('.save-row__content')).toHaveAttribute('aria-pressed', 'true');
});
test('JRN-SAVE-11 deletes selected and last snapshots with detail and route fallback', async ({ page }) => {
  await openJourney(page, 'saves');
  const before = await fileSnapshot(page);
  await snapshotRow(page, 'Opening').locator('.save-row__content').click();
  await deleteSnapshot(page, 'Opening');
  expect(await fileSnapshot(page)).toEqual(Object.fromEntries(Object.entries(before).filter(([path]) => path !== 'saves/save-library/Opening.json')));
  await expect(page.getByLabel('Selected save details')).toContainText('4 plies');
  await expect(page.getByLabel('Selected save details').getByRole('heading')).toHaveText('Middlegame');
  await deleteSnapshot(page, 'Middlegame');
  await deleteSnapshot(page, 'Automatic save');
  await expect(page).toHaveURL(/\/saved-games\/load$/);
  await expect(page.locator('.game-row')).toHaveCount(1);
  await expect(page.getByLabel('Selected save details')).toHaveCount(0);
  expect(await readFile(page, 'saves/save-other/Named save.json')).toBe(before['saves/save-other/Named save.json']);
});
test('JRN-SAVE-12 empties the library while preserving an open playable workspace across load and save routes', async ({ page }) => {
  await openJourney(page, 'saves');
  for (const name of ['Opening', 'Middlegame', 'Automatic save']) await deleteSnapshot(page, name);
  await page.locator('.game-row').click();
  await page.getByRole('button', { name: 'Select game', exact: true }).click();
  for (const name of ['Mismatched', 'Named save', 'Automatic save']) await deleteSnapshot(page, name);
  await expect(page).toHaveURL(/\/saved-games\/load$/);
  await expect(page.getByText('No saved games yet', { exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Select game', exact: true })).toBeDisabled();
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  await expect(page.getByText('Current workspace', { exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Save game', exact: true })).toBeEnabled();
  await page.locator('.app-header').getByRole('button', { name: 'Load', exact: true }).click();
  await expect(page.getByText('No saved games yet', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Close', exact: true }).click();
  await expect(page).toHaveURL(/\/game\/save-library$/);
  await expect(square(page, 'f3')).toHaveAttribute('aria-label', 'f3 white knight');
  await playMove(page, 'f1', 'b5');
  await expect(square(page, 'b5')).toHaveAttribute('aria-label', 'b5 white bishop');
});
