import { test, expect } from './StorageTest';
import { readFile } from '../../support/SaveInspection';
import { waitForJourney } from '../../support/JourneyBootstrap';
import { failNext, managedSnapshot, openStorageGame } from './StorageAction';
test('JRN-IO-03 preserves accepted preferences and the editable draft after failed Apply then retries and reloads', async ({ page }) => {
  await openStorageGame(page);
  const before = await readFile(page, 'settings.json');
  const games = await managedSnapshot(page);
  await page.getByRole('button', { name: 'Settings', exact: true }).click();
  await page.getByRole('button', { name: 'Appearance', exact: true }).click();
  const theme = await page.locator('html').getAttribute('data-theme');
  const nextTheme = theme === 'dark' ? 'light' : 'dark';
  await page.getByRole('radio', { name: nextTheme, exact: true }).check();
  await failNext(page, 'writeTextFile', 'settings.json');
  await page.getByRole('button', { name: 'Apply changes', exact: true }).click();
  await expect(page.locator('.settings-feedback--error')).toContainText('Try again');
  await expect(page.getByRole('radio', { name: nextTheme, exact: true })).toBeChecked();
  await expect(page.getByRole('button', { name: 'Apply changes', exact: true })).toBeEnabled();
  await expect(page.locator('html')).toHaveAttribute('data-theme', theme!);
  expect(await readFile(page, 'settings.json')).toBe(before);
  await page.getByRole('button', { name: 'Gameplay', exact: true }).click();
  await page.getByRole('button', { name: 'Appearance', exact: true }).click();
  await expect(page.getByRole('radio', { name: nextTheme, exact: true })).toBeChecked();
  await page.getByRole('button', { name: 'Apply changes', exact: true }).click();
  await expect(page.locator('html')).toHaveAttribute('data-theme', nextTheme);
  expect(JSON.parse((await readFile(page, 'settings.json'))!).appearance.themeMode).toBe(nextTheme);
  expect(await managedSnapshot(page)).toEqual(games);
  await page.reload();
  await waitForJourney(page);
  await expect(page.getByRole('radio', { name: nextTheme, exact: true })).toBeChecked();
  await expect(page.locator('html')).toHaveAttribute('data-theme', nextTheme);
});
