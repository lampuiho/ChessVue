import { test, expect } from './SettingsTest';
import { openJourney, waitForJourney } from '../../support/JourneyBootstrap';
import { saveCurrentGame } from '../../support/GameSave';
import { acceptedSettings, addOption, applySettings, editProfile, returnToGame, saveProfile } from './SettingsAction';
test('JRN-SETTINGS-10 preserves typed and empty options through reload and engine initialisation', async ({ page }) => {
  await openJourney(page, 'settings');
  const editor = await editProfile(page, 'Journey A');
  await editor.getByPlaceholder('Value', { exact: true }).first().fill('2');
  await editor.locator('.option-list > div').nth(1).getByRole('button').click();
  for (const [name, value] of [['Ponder', 'true'], ['AnalyseMode', 'false'], ['Contempt', '-1.5'], ['BookFile', ' book.bin '], ['Empty', '']]) await addOption(editor, name!, value!);
  await saveProfile(editor);
  await applySettings(page);
  const options = { MultiPV: 2, Ponder: true, AnalyseMode: false, Contempt: -1.5, BookFile: ' book.bin ', Empty: '' };
  expect((await acceptedSettings(page)).analysis.engineInventory[0]!.options).toEqual(options);
  await page.reload();
  await waitForJourney(page);
  const reopened = await editProfile(page, 'Journey A');
  await expect(reopened.getByPlaceholder('Value', { exact: true }).last()).toHaveValue('');
  await reopened.getByRole('button', { name: 'Cancel', exact: true }).click();
  await returnToGame(page);
  await page.getByRole('button', { name: /^Analyse Explore/ }).click();
  await page.getByRole('button', { name: 'Add engine', exact: true }).first().click();
  await page.getByRole('radio', { name: /Journey A/ }).check();
  await page.getByRole('dialog').getByRole('button', { name: 'Add engine', exact: true }).click();
  await expect(page.locator('.engine-summary')).toContainText('Depth 12');
  const seat = (await saveCurrentGame(page, 'Typed option output')).analysis.seats[0]!;
  expect(seat.assignedEngine.options).toEqual(options);
  expect(seat.lines).toHaveLength(3);
  expect((await acceptedSettings(page)).analysis.engineInventory[0]!.options).toEqual(options);
});
