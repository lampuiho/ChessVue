import { test, expect } from './RaceTest';
import { openAnalysisRace, analysisSeat, release, emit, latestSearch } from './RaceAction';
import { saveCurrentGame } from '../../support/GameSave';
test('JRN-RACE-08 stops and removes pending work without accepting late output', async ({ page }) => {
  const [a, b] = await openAnalysisRace(page);
  await release(page, a!.id);
  await release(page, b!.id);
  await page.evaluate(() => window.chessVueJourney.engines.holdStops(true));
  await analysisSeat(page).getByRole('button', { name: 'Stop engine', exact: true }).click();
  await emit(page, a!.id, 'info depth 90 score cp 999 pv g1f3');
  await release(page, a!.id);
  await expect(analysisSeat(page).locator('.engine-section__status--ready')).toBeVisible();
  await emit(page, a!.id, 'info depth 91 score cp 999 pv g1f3');
  await expect(analysisSeat(page).locator('.engine-section__score')).toHaveText('+0.24');
  await page.evaluate(() => window.chessVueJourney.engines.holdStops(false));
  await page.getByRole('button', { name: 'Refresh analysis', exact: true }).click();
  const pending = await latestSearch(page, 'analysis', 'journey://a', b!.id);
  await analysisSeat(page).getByRole('button', { name: 'Remove engine', exact: true }).click();
  await expect(analysisSeat(page)).toHaveCount(0);
  await expect.poll(() => page.evaluate((id) => window.chessVueJourney.engines.processes().find((p) => p.id === id), pending.processId)).toMatchObject({ closed: true, searching: false, pendingTimer: false, listeners: 0 });
  await emit(page, pending.id, 'info depth 92 score cp 999 pv g1f3');
  await emit(page, pending.id, 'bestmove g1f3');
  const currentB = await latestSearch(page, 'analysis', 'journey://b', b!.id);
  await release(page, currentB.id);
  const saved = await saveCurrentGame(page, 'cleaned-runtime');
  expect(saved.analysis.seats).toHaveLength(1);
  expect(saved.analysis.seats[0]!.assignedEngine.displayName).toBe('Journey B');
  expect(saved.analysis.seats[0]!.lines[0]!.depth).toBe(12);
  expect(saved.renderedPath).toEqual([0, 0]);
});
