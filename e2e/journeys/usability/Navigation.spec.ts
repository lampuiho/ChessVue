import { test, expect } from './UsabilityTest';
import { openJourney } from '../../support/JourneyBootstrap';
import { expectReachable, expectViewport } from './LayoutAction';
test('JRN-UX-03 fits the desktop workspace with collapsed and expanded left navigation', async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 1280, height: 720 });
  await openJourney(page, 'usability');
  const rail = page.locator('.navigation-frame');
  const collapsed = (await rail.boundingBox())!;
  await expect(rail).toHaveCSS('position', 'static');
  await page.getByRole('button', { name: 'Expand navigation', exact: true }).click();
  const expanded = (await rail.boundingBox())!;
  expect(expanded.width).toBeGreaterThan(collapsed.width * 2);
  expect((await page.locator('.game-content').boundingBox())!.x).toBeGreaterThanOrEqual(expanded.width);
  await expectReachable(page, page.locator('.player-panel').last());
  await expectReachable(page, page.locator('.control-panel').getByRole('button').last());
  await expectReachable(page, page.getByRole('button', { name: 'Collapse history', exact: true }));
  await expectReachable(page, page.getByRole('button', { name: 'Collapse analysis', exact: true }));
  await testInfo.attach('expanded-navigation', { body: await page.screenshot(), contentType: 'image/png' });
  await page.getByRole('button', { name: 'Settings', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Collapse navigation', exact: true })).toBeVisible();
  await expectReachable(page, page.getByRole('button', { name: 'Apply changes', exact: true }));
  await page.getByRole('button', { name: 'Back to game', exact: true }).click();
  await page.getByRole('button', { name: 'Collapse navigation', exact: true }).click();
  await expect(rail).toHaveCSS('width', `${collapsed.width}px`);
  await expectViewport(page);
});
for (const height of [667, 812]) test(`JRN-UX-03 fits mobile at 375x${height} with an accessible overlay menu`, async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 375, height });
  await openJourney(page, 'usability');
  await expectViewport(page);
  await expectReachable(page, page.locator('.player-panel').last());
  await expectReachable(page, page.locator('.control-panel').getByRole('button').last());
  await expectReachable(page, page.getByRole('button', { name: 'Collapse history', exact: true }));
  await expectReachable(page, page.getByRole('button', { name: 'Collapse analysis', exact: true }));
  await expect(page.locator('.navigation-frame')).toHaveCSS('flex-direction', 'row');
  const opener = page.getByRole('button', { name: 'Open navigation menu', exact: true });
  await opener.click();
  const drawer = page.getByRole('dialog', { name: 'Navigation menu', exact: true });
  await expect(drawer).toBeVisible();
  await expect(drawer.getByRole('button', { name: 'Close navigation menu', exact: true })).toBeFocused();
  await page.keyboard.press('Shift+Tab');
  await expect(drawer.getByRole('button', { name: 'Settings', exact: true })).toBeFocused();
  await page.keyboard.press('Escape');
  await expect(drawer).toHaveCount(0);
  await expect(opener).toBeFocused();
  await opener.click();
  await testInfo.attach('mobile-menu', { body: await page.screenshot(), contentType: 'image/png' });
  await page.locator('.navigation-overlay').click({ position: { x: 374, y: height / 2 } });
  await expect(opener).toBeFocused();
  await opener.click();
  await drawer.getByRole('button', { name: 'Load', exact: true }).click();
  await expect(drawer).toHaveCount(0);
  await expectReachable(page, page.getByRole('button', { name: 'Select game', exact: true }));
  await page.getByRole('button', { name: 'Close', exact: true }).click();
  await expectReachable(page, page.locator('.board-grid'));
  await testInfo.attach('mobile-workspace', { body: await page.screenshot(), contentType: 'image/png' });
  await opener.click();
  await drawer.getByRole('button', { name: 'Custom', exact: true }).click();
  await expect(drawer).toHaveCount(0);
  const creation = page.getByRole('dialog', { name: 'Set up a new board', exact: true });
  await expect(creation.getByLabel('Name', { exact: false })).toBeFocused();
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  await expectReachable(page, page.getByLabel('Save name', { exact: false }));
  await expectReachable(page, page.getByRole('button', { name: 'Save game', exact: true }));
  await page.getByRole('button', { name: 'Close', exact: true }).click();
  await page.getByRole('button', { name: 'Settings', exact: true }).click();
  await page.getByRole('button', { name: 'Appearance', exact: true }).click();
  await expectReachable(page, page.getByRole('button', { name: 'Apply changes', exact: true }));
  await page.getByRole('button', { name: 'Back to game', exact: true }).click();
  await expectReachable(page, page.locator('.analysis-list .panel-empty strong'));
  await opener.click();
  await page.setViewportSize({ width: 1024, height: 768 });
  await expect(drawer).toBeVisible();
  await expect(drawer.getByRole('button', { name: 'Close navigation menu', exact: true })).toBeFocused();
  await page.keyboard.press('Escape');
  await expect(page.getByRole('button', { name: 'Expand navigation', exact: true })).toBeFocused();
});
for (const [width, height] of [[1024, 768], [375, 667]] as const) {
  test(`JRN-UX-03 keeps the position editor and palette within ${width}x${height}`, async ({ page }, testInfo) => {
    await page.setViewportSize({ width, height });
    await openJourney(page, 'setup');
    await page.getByRole('button', { name: /Edit board/ }).click();
    await expectReachable(page, page.locator('.board-grid'));
    await expectReachable(page, page.locator('.player-panel').last());
    await expectReachable(page, page.locator('.piece-palette').getByRole('button', { name: 'Reset', exact: true }));
    await expectReachable(page, page.getByRole('button', { name: /Finish editing/ }));
    for (const identity of await page.locator('.player-identity').all()) {
      expect(await identity.evaluate((element) => element.getBoundingClientRect().height <= element.parentElement!.getBoundingClientRect().height)).toBe(true);
    }
    await testInfo.attach('position-editor', { body: await page.screenshot(), contentType: 'image/png' });
  });
  test(`JRN-UX-03 fits Home and its start actions within ${width}x${height}`, async ({ page }) => {
    await page.setViewportSize({ width, height });
    await openJourney(page, 'sessions');
    await expectReachable(page, page.locator('.home-title'));
    for (const action of await page.locator('.home-action').all()) await expectReachable(page, action);
    await expectReachable(page, page.locator('.home-footer'));
  });
}
