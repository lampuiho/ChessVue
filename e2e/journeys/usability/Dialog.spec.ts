import { test, expect } from './UsabilityTest';
import { keyboardActivate, expectFocusCycle, expectFocusInside } from './KeyboardAction';
import { openJourney } from '../../support/JourneyBootstrap';
test('JRN-UX-02 contains overwrite errors, restores focus and commits repeated confirmation once', async ({ page }) => {
  await openJourney(page, 'storage-failures');
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  await page.getByLabel('Save name', { exact: false }).fill('Opening');
  const save = page.getByRole('button', { name: 'Save game', exact: true });
  await save.click();
  const dialog = page.getByRole('dialog', { name: 'Replace this save?', exact: true });
  await expectFocusInside(dialog);
  await expectFocusCycle(page, dialog);
  await page.keyboard.press('Escape');
  await expect(dialog).toHaveCount(0);
  await expect(save).toBeFocused();
  await page.keyboard.press('Enter');
  await page.evaluate(() => window.chessVueJourney.storage.failNext('writeTextFile', 'saves/io-game/Opening.json'));
  const replace = dialog.getByRole('button', { name: 'Replace save', exact: true });
  await keyboardActivate(page, replace);
  await expect(dialog.getByRole('alert')).toBeVisible();
  await expectFocusInside(dialog);
  const held = await page.evaluate(() => window.chessVueJourney.storage.holdNext('writeTextFile', 'saves/io-game/Opening.json'));
  await replace.evaluate((button) => { button.dispatchEvent(new MouseEvent('click', { bubbles: true })); button.dispatchEvent(new MouseEvent('click', { bubbles: true })); });
  await expect.poll(() => page.evaluate(() => window.chessVueJourney.storage.operations().filter((operation) => operation.path === 'saves/io-game/Opening.json' && operation.operation === 'writeTextFile').map((operation) => operation.state))).toEqual(['failed', 'held']);
  await expect(replace).toBeDisabled();
  await expectFocusInside(dialog);
  await page.keyboard.press('Escape');
  await expect(dialog).toBeVisible();
  await page.evaluate((id) => window.chessVueJourney.storage.release(id), held);
  await expect(dialog).toHaveCount(0);
  await expect(save).toBeFocused();
  await expect(page.locator('.library-feedback')).toContainText('Opening');
});
test('JRN-UX-02 contains import errors and returns focus after Escape and backdrop dismissal', async ({ page }) => {
  await openJourney(page, 'saves');
  await page.evaluate(() => window.chessVueJourney.chooseImport('imports/corrupt.json'));
  const launch = page.getByRole('button', { name: 'Import file', exact: true });
  const dialog = page.getByRole('dialog', { name: 'Could not import game', exact: true });
  for (const dismissal of ['escape', 'backdrop']) {
    await launch.click();
    await expectFocusInside(dialog);
    await expectFocusCycle(page, dialog);
    if (dismissal === 'escape') await page.keyboard.press('Escape');
    else await page.locator('.modal-backdrop').click({ position: { x: 2, y: 2 } });
    await expect(dialog).toHaveCount(0);
    await expect(launch).toBeFocused();
  }
});
test('JRN-UX-02 keeps dirty-settings cancellation in its owner and restores the return action', async ({ page }) => {
  await openJourney(page, 'settings');
  await page.getByRole('button', { name: 'Gameplay', exact: true }).click();
  await page.getByLabel('Game name', { exact: true }).fill('Unapplied name');
  const launch = page.getByRole('button', { name: 'Back to game', exact: true });
  await launch.click();
  const dialog = page.getByRole('dialog', { name: 'Discard unsaved changes?', exact: true });
  await expectFocusInside(dialog);
  await expectFocusCycle(page, dialog);
  await keyboardActivate(page, dialog.getByRole('button', { name: 'Keep editing', exact: true }));
  await expect(launch).toBeFocused();
  await expect(page.getByLabel('Game name', { exact: true })).toHaveValue('Unapplied name');
  await page.keyboard.press('Enter');
  await keyboardActivate(page, dialog.getByRole('button', { name: 'Discard changes', exact: true }));
  await expect(page).toHaveURL(/\/game\/settings-game$/);
});
test('JRN-UX-02 transfers focus into draw resolution and requires an explicit response', async ({ page }) => {
  await openJourney(page, 'play');
  const launch = page.getByRole('button', { name: 'Offer draw', exact: true });
  await launch.click();
  const offer = page.getByRole('dialog', { name: 'Offer a draw?', exact: true });
  await expectFocusInside(offer);
  await keyboardActivate(page, offer.getByRole('button', { name: 'Offer draw', exact: true }));
  const resolve = page.getByRole('dialog', { name: 'Draw offered', exact: true });
  await expectFocusInside(resolve);
  await expectFocusCycle(page, resolve);
  await expect(resolve.getByRole('button', { name: 'Close dialog', exact: true })).toHaveCount(0);
  await page.keyboard.press('Escape');
  await page.locator('.modal-backdrop').click({ position: { x: 2, y: 2 } });
  await expect(resolve).toBeVisible();
  await keyboardActivate(page, resolve.getByRole('button', { name: 'Decline', exact: true }));
  await expect(resolve).toHaveCount(0);
  await expect(launch).toBeFocused();
  await expect(page.locator('.result-badge')).toContainText('to move');
});
