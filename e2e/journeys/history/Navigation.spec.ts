import { test, expect, historyTime } from './HistoryTest';
import { openJourney } from '../../support/JourneyBootstrap';
import { playMove, square } from '../../support/BoardInteraction';
import { saveCurrentGame } from '../../support/GameSave';
import { createTimedHistory, historyRow, returnLive } from './HistorySetup';

test('JRN-HIST-01 reviews root, mainline, sibling and nested positions without changing live history', async ({ page }) => {
  await openJourney(page, 'history');
  await playMove(page, 'b5', 'c6');
  const before = await saveCurrentGame(page, 'before-review');
  await expect(page.getByLabel('Captured material')).toHaveCount(1);
  await page.getByRole('button', { name: 'Collapse history', exact: true }).click();
  await expect(page.locator('.history-row')).toHaveCount(0);
  await page.getByRole('button', { name: 'Expand history', exact: true }).click();
  await page.getByRole('button', { name: 'Start position', exact: true }).click();
  await expect(page.locator('.history-start')).toHaveClass(/history-row--selected/);
  await expect(square(page, 'e2')).toHaveAttribute('aria-label', 'e2 white pawn');
  await expect(page.locator('.board-square--last')).toHaveCount(0);
  await expect(page.getByLabel('Captured material')).toHaveCount(0);
  await historyRow(page, 'Nf3').first().click();
  await expect(square(page, 'f3')).toHaveAttribute('aria-label', 'f3 white knight');
  await expect(square(page, 'f3')).toHaveClass(/board-square--last/);
  await historyRow(page, 'c5').click();
  await expect(square(page, 'c5')).toHaveAttribute('aria-label', 'c5 black pawn');
  await expect(square(page, 'g1')).toHaveAttribute('aria-label', 'g1 white knight');
  await historyRow(page, 'Nc3').click();
  await expect(page.locator('.history-row--selected')).toContainText('Nc3');
  await expect(square(page, 'c3')).toHaveAttribute('aria-label', 'c3 white knight');
  await expect(square(page, 'c4')).toHaveAttribute('aria-label', 'c4 white bishop');
  await expect(square(page, 'f6')).toHaveAttribute('aria-label', 'f6 black knight');
  await returnLive(page);
  await expect(page.locator('.history-row--selected')).toContainText('Bxc6');
  await expect(square(page, 'c6')).toHaveAttribute('aria-label', 'c6 white bishop');
  await expect(page.getByLabel('Captured material')).toHaveCount(1);
  const after = await saveCurrentGame(page, 'after-review');
  expect(after.moveTree).toEqual(before.moveTree);
  expect(after.livePath).toEqual(before.livePath);
});
test('JRN-HIST-01 keeps the live clock running during ordinary timed history review', async ({ page }) => {
  await openJourney(page, 'history');
  await createTimedHistory(page);
  await historyRow(page, 'e4').click();
  await expect(square(page, 'e7')).toHaveAttribute('aria-label', 'e7 black pawn');
  await page.clock.setFixedTime(new Date(historyTime.getTime() + 3000));
  await page.clock.runFor(300);
  await expect(page.locator('.player-clock').last()).toContainText('4:59');
  await returnLive(page);
  await expect(square(page, 'e5')).toHaveAttribute('aria-label', 'e5 black pawn');
  const saved = await saveCurrentGame(page, 'timed-review');
  expect(saved.livePath).toEqual([0, 0]);
  expect(saved.clockSnapshot.white.remainingMs).toBe(299000);
  expect(saved.clockSnapshot.black.remainingMs).toBe(302000);
});
