import { test, expect } from './AnalysisTest';
import { openJourney } from '../../support/JourneyBootstrap';
import { saveCurrentGame } from '../../support/GameSave';
import { configureEngines } from '../../support/EngineInventory';
import { selectGame } from '../../support/GameNavigation';
import { addEngine, analysisSeat, expectOutput } from './AnalysisAction';
test('JRN-ANALYSIS-07 stops refreshes and removes one seat without stopping its neighbour', async ({ page }) => {
  await openJourney(page, 'analysis');
  await expectOutput(page);
  const before = await saveCurrentGame(page, 'before-stop');
  await analysisSeat(page).getByRole('button', { name: 'Stop engine', exact: true }).click();
  await expect(analysisSeat(page).getByRole('button', { name: 'Stop engine', exact: true })).toHaveCount(0);
  await expect(analysisSeat(page).locator('.engine-section__status--ready')).toHaveCount(1);
  await expectOutput(page, ['Journey B']);
  const stopped = await saveCurrentGame(page, 'stopped-seat');
  expect(stopped.analysis.seats[0]!.lines).toEqual(before.analysis.seats[0]!.lines);
  await page.getByRole('button', { name: 'Refresh analysis', exact: true }).click();
  await expectOutput(page);
  await analysisSeat(page).getByRole('button', { name: 'Remove engine', exact: true }).click();
  await expect(analysisSeat(page)).toHaveCount(0);
  await page.getByRole('button', { name: 'Refresh analysis', exact: true }).click();
  await expectOutput(page, ['Journey B']);
  const removed = await saveCurrentGame(page, 'removed-seat');
  expect(removed.analysis.seats.map((seat) => seat.assignedEngine.displayName)).toEqual(['Journey B']);
  expect(removed.moveTree).toEqual(before.moveTree);
  expect(removed.renderedPath).toEqual(before.renderedPath);
});
test('JRN-ANALYSIS-08 blocks duplicate and fifth assignments while four distinct seats operate', async ({ page }) => {
  await openJourney(page, 'analysis');
  await configureEngines(page, [{ name: 'Journey C', path: 'journey://a' }, { name: 'Journey D', path: 'journey://b' }, { name: 'Journey E', path: 'journey://a' }]);
  await selectGame(page, 'analysis-free', 'Free analysis with two engines');
  await page.getByRole('button', { name: 'Add engine', exact: true }).first().click();
  const dialog = page.getByRole('dialog', { name: 'Add analysis engine', exact: true });
  await expect(dialog.getByRole('radio', { name: /Journey A / })).toHaveCount(0);
  await expect(dialog.getByRole('radio', { name: /Journey B / })).toHaveCount(0);
  await expect(dialog.getByRole('button', { name: 'Add engine', exact: true })).toBeDisabled();
  await dialog.getByRole('button', { name: 'Cancel', exact: true }).click();
  await addEngine(page, 'Journey C');
  await addEngine(page, 'Journey D');
  await expectOutput(page, ['Journey A', 'Journey B', 'Journey C']);
  await expect(analysisSeat(page, 'Journey D').locator('.analysis-line')).toHaveCount(3);
  await expect(analysisSeat(page, 'Journey D').locator('.engine-section__score')).toHaveText('+0.36');
  await expect(page.getByRole('button', { name: 'Add engine', exact: true })).toBeDisabled();
  const full = await saveCurrentGame(page, 'four-seats');
  expect(full.analysis.seats.map((seat) => seat.assignedEngine.displayName)).toEqual(['Journey A', 'Journey B', 'Journey C', 'Journey D']);
  await analysisSeat(page, 'Journey C').getByRole('button', { name: 'Stop engine', exact: true }).click();
  for (const name of ['Journey A', 'Journey B', 'Journey D']) await expect(analysisSeat(page, name).getByRole('button', { name: 'Stop engine', exact: true })).toBeVisible();
  await analysisSeat(page, 'Journey D').getByRole('button', { name: 'Remove engine', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Add engine', exact: true })).toBeEnabled();
  await addEngine(page, 'Journey E');
  await expectOutput(page, ['Journey E']);
  const replaced = await saveCurrentGame(page, 'replacement-seat');
  expect(replaced.analysis.seats.map((seat) => seat.assignedEngine.displayName)).toEqual(['Journey A', 'Journey B', 'Journey C', 'Journey E']);
  expect(replaced.moveTree).toEqual(full.moveTree);
});
test('JRN-ANALYSIS-09 isolates unavailable engine retry and recovers by removing the failed seat', async ({ page }) => {
  await openJourney(page, 'analysis');
  await expectOutput(page);
  const before = await saveCurrentGame(page, 'before-failure');
  await addEngine(page, 'Journey unavailable');
  const failed = analysisSeat(page, 'Journey unavailable');
  await expect(failed.locator('.engine-error')).toContainText('Process failed to start: journey://unavailable');
  await expect(failed.locator('.engine-summary')).toContainText('Analysis failed');
  await expectOutput(page);
  await failed.getByRole('button', { name: 'Retry engine', exact: true }).click();
  await expect(failed.locator('.engine-error')).toContainText('Process failed to start: journey://unavailable');
  await expect(failed.getByRole('button', { name: 'Retry engine', exact: true })).toBeEnabled();
  await page.getByRole('button', { name: 'Refresh analysis', exact: true }).click();
  await expectOutput(page);
  await failed.getByRole('button', { name: 'Remove engine', exact: true }).click();
  await expect(failed).toHaveCount(0);
  const after = await saveCurrentGame(page, 'recovered-output');
  expect(after.analysis.seats.map((seat) => seat.assignedEngine)).toEqual(before.analysis.seats.map((seat) => seat.assignedEngine));
  expect(after.moveTree).toEqual(before.moveTree);
  expect(after.renderedPath).toEqual(before.renderedPath);
});
