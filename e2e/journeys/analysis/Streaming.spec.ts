test('JRN-ANALYSIS-02 folds one engine and the panel while refreshed output continues', async ({ page }) => {
  await openJourney(page, 'analysis');
  await expectOutput(page);
  await page.clock.pauseAt(new Date(analysisTime.getTime() + 60000));
  await analysisSeat(page).getByRole('button', { name: 'Journey A', exact: true }).click();
  await expect(analysisSeat(page).locator('.analysis-line')).toHaveCount(0);
  await expect(analysisSeat(page, 'Journey B').locator('.analysis-line')).toHaveCount(3);
  await page.getByRole('button', { name: 'Refresh analysis', exact: true }).click();
  await page.getByRole('button', { name: 'Collapse analysis', exact: true }).click();
  await page.clock.runFor(200);
  const folded = await saveCurrentGame(page, 'folded-output');
  expect(folded.analysis.seats.map((seat) => seat.lines.length)).toEqual([3, 3]);
  expect(folded.renderedPath).toEqual([0, 0]);
  await page.getByRole('button', { name: 'Expand analysis', exact: true }).click();
  await expect(analysisSeat(page).locator('.analysis-line')).toHaveCount(0);
  await expect(analysisSeat(page, 'Journey B').locator('.analysis-line')).toHaveCount(3);
  await analysisSeat(page).getByRole('button', { name: 'Journey A', exact: true }).click();
  await expectOutput(page);
  const reopened = await saveCurrentGame(page, 'reopened-output');
  expect(reopened.analysis).toEqual(folded.analysis);
  expect(reopened.moveTree).toEqual(folded.moveTree);
});
test('JRN-ANALYSIS-12 clears unevaluated history selections and rejects superseded output during rapid navigation', async ({ page }) => {
  await openJourney(page, 'analysis');
  await selectAnalysisGame(page);
  await expectOutput(page);
  await page.clock.pauseAt(new Date(analysisTime.getTime() + 60000));
  await page.getByRole('button', { name: 'Start position', exact: true }).click();
  await expect(page.locator('.analysis-line')).toHaveCount(0);
  await expect(page.locator('.engine-summary')).toHaveCount(2);
  await expect(page.locator('.engine-summary').first()).toContainText('No principal variation yet');
  await expect(page.locator('.engine-section__score').first()).toHaveText('—');
  await page.locator('.history-row').filter({ has: page.locator('strong').getByText('e4', { exact: true }) }).click();
  await page.getByRole('button', { name: 'Live position', exact: true }).click();
  await page.locator('.history-row').filter({ has: page.locator('strong').getByText('e4', { exact: true }) }).click();
  await expect(page.locator('.analysis-line')).toHaveCount(0);
  await page.clock.runFor(200);
  await expectOutput(page, undefined, 'black');
  await expect(page.locator('.history-row--selected')).toContainText('e4');
  const selected = await saveCurrentGame(page, 'selected-node');
  expect(selected.renderedPath).toEqual([0]);
  expect(selected.livePath).toEqual([0, 0]);
  expect(nodeAt(selected, [0]).recordedAnalysis).toBeUndefined();
  for (const seat of selected.analysis.seats) for (const line of seat.lines) expect(line.pv[0]!.movingColour).toBe('black');
});
for (const showMoves of [false, true]) {
  test(`keeps White's score perspective after live moves with suggestions ${showMoves ? 'enabled' : 'disabled'}`, async ({ page }) => {
    await openJourney(page, 'analysis');
    await selectAnalysisGame(page, showMoves);
    await expect(analysisSeat(page).locator('.engine-section__score')).toHaveText('+0.24');
    await expect(page.locator('.analysis-panel .side-panel__meta')).toContainText('White perspective');
    await playMove(page, 'g1', 'f3');
    await expect(page.locator('.result-badge')).toHaveText('black to move');
    await expect(analysisSeat(page).locator('.engine-section__score')).toHaveText('−0.24');
    if (showMoves) await expect(analysisSeat(page).locator('.analysis-line__score')).toHaveText(['−0.24', '−0.06', '+0.12']);
    const saved = await saveCurrentGame(page, 'black-to-move-scores');
    expect(saved.analysis.seats[0]!.lines[0]!.scoreCp).toBe(24);
    expect(saved.analysis.seats[0]!.lines[0]!.pv[0]!.movingColour).toBe('black');
    await playMove(page, 'b8', 'c6');
    await expect(page.locator('.result-badge')).toHaveText('white to move');
    await expect(analysisSeat(page).locator('.engine-section__score')).toHaveText('+0.24');
  });
}
