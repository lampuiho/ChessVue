import { test, expect } from './PlayTest';
import { openJourney } from '../../support/JourneyBootstrap';
import { playMove, square } from '../../support/BoardInteraction';
import { saveCurrentGame } from '../../support/GameSave';
import { autoSave, createTimedPlay, playTime } from './PlaySetup';

test('JRN-PLAY-01 @smoke commits one opening move with captures and immediate feedback', async ({ page }) => {
  await openJourney(page, 'play');
  await playMove(page, 'g1', 'f3');
  await expect(square(page, 'f3')).toHaveAttribute('aria-label', 'f3 white knight');
  await expect(square(page, 'g1')).toHaveAttribute('aria-label', 'g1');
  await expect(page.locator('.history-row')).toHaveCount(5);
  await expect(page.locator('.history-row--selected')).toContainText('Nf3');
  await expect(page.locator('.result-badge')).toHaveText('black to move');
  await expect(page.locator('.player-panel--active .player-name')).toHaveText('Black');
  await expect(page.locator('.captured-pieces')).toHaveCount(2);
  await expect(page.locator('.captured-pieces').nth(0)).toHaveText('♙');
  await expect(page.locator('.captured-pieces').nth(1)).toHaveText('♟');
  await expect(page.locator('.board-square--selected')).toHaveCount(0);
  await expect(page.locator('.board-square--last')).toHaveCount(2);
  await expect(square(page, 'f3')).toHaveClass(/board-square--last/);
  await expect(square(page, 'g1')).toHaveClass(/board-square--last/);
  expect((await autoSave(page, 'play-opening')).livePath).toEqual([0, 0, 0, 0, 0]);
});
test('JRN-PLAY-02 rejects invalid clicks without adding time or history', async ({ page }) => {
  await openJourney(page, 'play');
  const id = await createTimedPlay(page);
  const before = await saveCurrentGame(page, 'before-invalid');
  await square(page, 'e2').click();
  await expect(square(page, 'e2')).toHaveClass(/board-square--selected/);
  await square(page, 'e2').click();
  await expect(page.locator('.board-square--selected, .board-square--target')).toHaveCount(0);
  await square(page, 'e2').click();
  await square(page, 'g1').click();
  await expect(square(page, 'g1')).toHaveClass(/board-square--selected/);
  await expect(square(page, 'e2')).not.toHaveClass(/board-square--selected/);
  await square(page, 'g5').click();
  await square(page, 'e7').click();
  await expect(page.locator('.board-square--selected, .board-square--target')).toHaveCount(0);
  await expect(page.locator('.history-row')).toHaveCount(0);
  await expect(page.locator('.player-clock').last()).toHaveText('5:00');
  expect((await saveCurrentGame(page, 'after-invalid')).moveTree).toEqual(before.moveTree);
  await page.clock.setFixedTime(new Date(playTime.getTime() + 1000));
  await playMove(page, 'e2', 'e4');
  await expect.poll(async () => (await autoSave(page, id)).clockSnapshot.white.remainingMs).toBe(301000);
  await expect(page.locator('.history-row')).toHaveCount(1);
});
test('JRN-PLAY-02 rejects wrong-colour drag and commits one valid drag', async ({ page }) => {
  await openJourney(page, 'play');
  const id = await createTimedPlay(page);
  await square(page, 'e7').locator('.chess-piece').dragTo(square(page, 'e5'));
  await expect(page.locator('.history-row')).toHaveCount(0);
  await expect(square(page, 'e7')).toHaveAttribute('aria-label', 'e7 black pawn');
  await square(page, 'e2').locator('.chess-piece').dragTo(square(page, 'e4'));
  await expect(page.locator('.history-row')).toHaveCount(1);
  await expect(square(page, 'e4')).toHaveAttribute('aria-label', 'e4 white pawn');
  await expect(page.locator('.result-badge')).toHaveText('black to move');
  expect((await autoSave(page, id)).clockSnapshot.white.remainingMs).toBe(302000);
});
