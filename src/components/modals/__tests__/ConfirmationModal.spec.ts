import { flushPromises, mount } from '@vue/test-utils';
import { expect, it, vi } from 'vitest';
import { Deferred } from '@/utility/async/Deferred';
import ConfirmationModal from '@/components/modals/ConfirmationModal.vue';
it('prevents duplicate confirmation and retains a failed operation for retry', async () => {
  const pending = new Deferred<void>();
  const confirm = vi.fn().mockImplementationOnce(() => pending).mockResolvedValue(undefined);
  const wrapper = mount(ConfirmationModal, { props: { title: 'Confirm', confirmLabel: 'Proceed', confirm, signal: new AbortController().signal } });
  const button = wrapper.findAll('button').find((item) => item.text() === 'Proceed')!;
  await button.trigger('click');
  await button.trigger('click');
  expect(confirm).toHaveBeenCalledOnce();
  pending.reject(new Error('Try again'));
  await flushPromises();
  expect(wrapper.text()).toContain('Try again');
  expect(wrapper.emitted('dismissed')).toBeUndefined();
  await button.trigger('click');
  await flushPromises();
  expect(wrapper.emitted('dismissed')).toHaveLength(1);
  wrapper.unmount();
});
it.each(['success', 'failure'])('ignores late %s delivery after dismissal', async (outcome) => {
  const pending = new Deferred<void>();
  const controller = new AbortController();
  const wrapper = mount(ConfirmationModal, { props: { title: 'Confirm', confirmLabel: 'Proceed', confirm: () => pending, signal: controller.signal } });
  await wrapper.findAll('button').find((item) => item.text() === 'Proceed')!.trigger('click');
  controller.abort();
  if (outcome === 'success') pending.resolve();
  else pending.reject(new Error('Old error'));
  await flushPromises();
  expect(wrapper.emitted('dismissed')).toBeUndefined();
  expect(wrapper.text()).not.toContain('Old error');
  wrapper.unmount();
});
it('blocks every dismissal while an overwrite is working and unlocks after failure', async () => {
  const pending = new Deferred<void>();
  const wrapper = mount(ConfirmationModal, { props: { title: 'Overwrite', confirmLabel: 'Replace', dismissibleWhileWorking: false, confirm: () => pending, signal: new AbortController().signal } });
  await wrapper.findAll('button').find((button) => button.text() === 'Replace')!.trigger('click');
  await wrapper.findAll('button').find((button) => button.text() === 'Cancel')!.trigger('click');
  await wrapper.get('[role="dialog"]').trigger('keydown', { key: 'Escape' });
  await wrapper.get('.modal-backdrop').trigger('mousedown');
  expect(wrapper.emitted('dismissed')).toBeUndefined();
  expect(wrapper.find('[aria-label="Close dialog"]').exists()).toBe(false);
  pending.reject(new Error('Write failed'));
  await flushPromises();
  expect(wrapper.get('[role="alert"]').text()).toBe('Write failed');
  await wrapper.findAll('button').find((button) => button.text() === 'Cancel')!.trigger('click');
  expect(wrapper.emitted('dismissed')).toHaveLength(1);
  wrapper.unmount();
});

it('preserves a typed native permission failure and permits confirmation retry', async () => {
  const message = 'File could not be written: protected.json.';
  const confirm = vi.fn().mockRejectedValueOnce({ kind: 'permissionDenied', operation: 'writeTextFile', message }).mockResolvedValue(undefined);
  const wrapper = mount(ConfirmationModal, { props: { title: 'Overwrite', confirmLabel: 'Replace', confirm, signal: new AbortController().signal } });
  const replace = wrapper.findAll('button').find(button => button.text() === 'Replace')!;
  await replace.trigger('click');
  await flushPromises();
  expect(wrapper.get('[role="alert"]').text()).toBe(message);
  expect(wrapper.emitted('dismissed')).toBeUndefined();
  await replace.trigger('click');
  await flushPromises();
  expect(wrapper.emitted('dismissed')).toHaveLength(1);
  wrapper.unmount();
});
