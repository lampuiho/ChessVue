import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
import { StoredWorkerUtility } from '../StoredWorkerUtility';

const _base = new URL('https://example.test/app/');
const _config = { databaseName: 'generic-test', storeName: 'assets', rootPath: 'stored-files', serviceWorkerPath: 'files.js' };
let library: StoredWorkerUtility;
function _environment(state: ServiceWorkerState = 'installing') {
  const worker = Object.assign(new EventTarget(), { state });
  const registration = { installing: worker, waiting: null, active: null, unregister: vi.fn().mockResolvedValue(true) } as unknown as ServiceWorkerRegistration;
  const container = Object.assign(new EventTarget(), { controller: null as unknown as ServiceWorker, register: vi.fn().mockResolvedValue(registration) });
  vi.stubGlobal('navigator', { serviceWorker: container });
  return { worker, registration, container };
}
beforeEach(() => { library = new StoredWorkerUtility(_config); });
afterEach(async () => { await library.dispose(); vi.restoreAllMocks(); vi.unstubAllGlobals(); });
describe('generic stored Worker library', () => {
  it('preserves literal special characters and a nested app base without encoding ordinary app URLs', () => {
    const url = library.resolveUrl('stored-files/Scripts % # \u68cb/nested/main.js', _base);
    expect(url.href).toBe('https://example.test/app/stored-files/Scripts%20%25%20%23%20%E6%A3%8B/nested/main.js');
    expect(library.isStoredUrl(url, _base)).toBe(true);
    expect(library.isStoredUrl(new URL('https://other.test/app/stored-files/a/b.js'), _base)).toBe(false);
    expect(library.isStoredUrl(new URL('https://example.test/stored-files/a/b.js'), _base)).toBe(false);
    expect(library.resolveUrl('ordinary/main.js?build=1', _base).href).toBe('https://example.test/app/ordinary/main.js?build=1');
    for (const path of ['stored-files/a/../main.js', 'stored-files/a/./main.js', 'stored-files/a//main.js', 'stored-files/a/\\main.js']) expect(() => library.resolveUrl(path, _base)).toThrow('Invalid stored file path');
  });
  it('passes storage configuration to the generic entry and waits for the matching active controller', async () => {
    const { worker, registration, container } = _environment();
    const removed = vi.spyOn(container, 'removeEventListener');
    const workerRemoved = vi.spyOn(worker, 'removeEventListener');
    let completed = false;
    const work = library.register(_base).then(() => { completed = true; });
    await Promise.resolve();
    worker.state = 'activated';
    Object.assign(registration, { active: worker as ServiceWorker });
    worker.dispatchEvent(new Event('statechange'));
    await Promise.resolve();
    expect(completed).toBe(false);
    container.controller = worker as ServiceWorker;
    container.dispatchEvent(new Event('controllerchange'));
    await work;
    const scriptUrl = new URL('files.js', _base);
    for (const key of ['databaseName', 'storeName', 'rootPath'] as const) scriptUrl.searchParams.set(key, _config[key]);
    expect(container.register).toHaveBeenCalledWith(scriptUrl, { scope: _base.href, type: 'module' });
    expect(removed).toHaveBeenCalledWith('controllerchange', expect.any(Function));
    expect(workerRemoved).toHaveBeenCalledWith('statechange', expect.any(Function));
    expect(registration.unregister).not.toHaveBeenCalled();
    await library.dispose();
    expect(registration.unregister).toHaveBeenCalledOnce();
    await library.dispose();
    expect(registration.unregister).toHaveBeenCalledOnce();
  });
  it('reports activation failure and explicit cancellation without releasing the manager-owned registration', async () => {
    const { worker, registration, container } = _environment();
    const failed = library.register(_base);
    await Promise.resolve();
    worker.state = 'redundant';
    worker.dispatchEvent(new Event('statechange'));
    await expect(failed).rejects.toThrow('failed to activate');
    const signalOwner = new AbortController();
    worker.state = 'installing';
    const pending = library.register(_base, signalOwner.signal);
    await Promise.resolve();
    const removed = vi.spyOn(container, 'removeEventListener');
    signalOwner.abort(new Error('Assignment cancelled.'));
    await expect(pending).rejects.toThrow('Assignment cancelled');
    expect(removed).toHaveBeenCalledWith('controllerchange', expect.any(Function));
    expect(registration.unregister).not.toHaveBeenCalled();
    await library.dispose();
    expect(registration.unregister).toHaveBeenCalledOnce();
  });
  it('disposes its own pending control wait without requiring a caller signal', async () => {
    const { worker, registration, container } = _environment();
    const removed = vi.spyOn(container, 'removeEventListener');
    const workerRemoved = vi.spyOn(worker, 'removeEventListener');
    const failed = expect(library.register(_base)).rejects.toThrow('loader was disposed');
    await Promise.resolve();
    await library.dispose();
    await failed;
    expect(removed).toHaveBeenCalledWith('controllerchange', expect.any(Function));
    expect(workerRemoved).toHaveBeenCalledWith('statechange', expect.any(Function));
    expect(registration.unregister).toHaveBeenCalledOnce();
    await expect(library.register(_base)).rejects.toThrow('loader was disposed');
    expect(container.register).toHaveBeenCalledOnce();
  });
  it('retains late native registration and awaits its actual unregistration', async () => {
    const { registration, container } = _environment();
    let deliver!: (registration: ServiceWorkerRegistration) => void;
    let unregistered!: (value: boolean) => void;
    container.register.mockImplementation(() => new Promise<ServiceWorkerRegistration>(resolve => { deliver = resolve; }));
    vi.mocked(registration.unregister).mockImplementation(() => new Promise<boolean>(resolve => { unregistered = resolve; }));
    const failed = expect(library.register(_base)).rejects.toThrow('loader was disposed');
    let disposed = false;
    const cleanup = library.dispose().then(() => { disposed = true; });
    await Promise.resolve();
    expect(disposed).toBe(false);
    expect(registration.unregister).not.toHaveBeenCalled();
    deliver(registration);
    await failed;
    expect(registration.unregister).toHaveBeenCalledOnce();
    expect(disposed).toBe(false);
    unregistered(true);
    await cleanup;
    expect(disposed).toBe(true);
  });
  it('keeps a failed unregister observable and retains the registration for an explicit cleanup retry', async () => {
    const { worker, registration, container } = _environment('activated');
    Object.assign(registration, { active: worker });
    container.controller = worker as ServiceWorker;
    await library.register(_base);
    vi.mocked(registration.unregister).mockRejectedValueOnce(new Error('Release failed.'));
    await expect(library.dispose()).rejects.toThrow('Release failed');
    await library.dispose();
    expect(registration.unregister).toHaveBeenCalledTimes(2);
    await library.dispose();
    expect(registration.unregister).toHaveBeenCalledTimes(2);
  });
  it('keeps a native registration failure as a launch error and has nothing to unregister', async () => {
    const { registration, container } = _environment();
    container.register.mockRejectedValueOnce(new Error('Registration denied.'));
    await expect(library.register(_base)).rejects.toThrow('Registration denied');
    await library.dispose();
    expect(registration.unregister).not.toHaveBeenCalled();
  });
  it('does no registration work when disposed or cancelled before the first registration', async () => {
    const { container } = _environment();
    const owner = new AbortController();
    owner.abort(new Error('Cancelled before launch.'));
    await expect(library.register(_base, owner.signal)).rejects.toThrow('Cancelled before launch');
    await library.dispose();
    await expect(library.register(_base)).rejects.toThrow('loader was disposed');
    expect(container.register).not.toHaveBeenCalled();
  });
});
